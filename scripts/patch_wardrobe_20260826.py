EXPECTED = {"items": 68, "noPhoto_true": 2,
            "verdicts": {"Keep": 45, "Tailor": 9, "Bin": 8, "Replace": 6},
            "scopes": {"core": 64, "out": 4}}

# ---------------------------------------------------------------- run
def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    path = pathlib.Path(sys.argv[1])
    commit = "--commit" in sys.argv
    data = json.loads(path.read_text(encoding="utf-8"))
    by_id = {it["id"]: it for it in data["items"]}

    missing = [k for k in EDITS if k not in by_id]
    if missing:
        sys.exit(f"STOP - ids not found in {path}: {missing}")

    changes = []
    for id_, patch in EDITS.items():
        it = by_id[id_]
        for field, value in patch.items():
            if field == "_append_notes":
                if value.strip()[:60] in it.get("notes", ""):
                    continue                          # idempotent
                it["notes"] = it.get("notes", "").rstrip() + value
                changes.append(f"{id_}.notes  += {value.strip()[:64]}...")
            else:
                if it.get(field) == value:
                    continue                          # idempotent
                changes.append(f"{id_}.{field}  {str(it.get(field))[:40]!r} -> {str(value)[:60]!r}")
                it[field] = value

    for dead in DELETE_IDS:
        if dead in by_id:
            data["items"] = [i for i in data["items"] if i["id"] != dead]
            changes.append(f"DELETED ITEM  {dead}  (phantom duplicate of trousers_01)")

    if data.get("generated") != "2026-08-26":
        changes.append(f"generated  {data.get('generated')!r} -> '2026-08-26'")
        data["generated"] = "2026-08-26"

    # ------------------------------------------------ verification
    items = data["items"]
    got = {"items": len(items),
           "noPhoto_true": sum(1 for i in items if i.get("noPhoto") is True),
           "verdicts": {}, "scopes": {}}
    for i in items:
        got["verdicts"][i["verdict"]] = got["verdicts"].get(i["verdict"], 0) + 1
        got["scopes"][i["scope"]] = got["scopes"].get(i["scope"], 0) + 1

    print(f"--- {len(changes)} change(s) ---")
    for c in changes:
        print("  ", c)

    print("\n--- reconciliation ---")
    ok = True
    for k, exp in EXPECTED.items():
        good = got[k] == exp
        ok &= good
        print(f"  {'OK ' if good else 'FAIL'}  {k}: got {got[k]}  expected {exp}")

    stale = [i["id"] for i in items if GROUP_NOTE_OLD in (i.get("notes") or "")
             or GROUP_NOTE_OLD in (i.get("photoRef") or "")]
    if stale:
        print(f"\n  WARNING - these still carry the false 'group photo is not on Drive' claim: {stale}")

    print("\n  items still without a photo (noPhoto=true):")
    for i in items:
        if i.get("noPhoto") is True:
            print(f"     {i['id']:46s} {i['verdict']:8s} {i['scope']:5s}  (not located 2026-08-26)")

    print("\n  files orphaned by this patch - park, do not silently delete:")
    for f in ORPHANED_BY_DELETE:
        print(f"     {f}")

    if not ok:
        sys.exit("\nSTOP - reconciliation failed. Do not commit. Investigate the mismatch.")

    out = path.with_suffix(path.suffix + ".new")
    if commit:
        shutil.copy2(path, path.with_suffix(path.suffix + ".bak"))
        out.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"\nWROTE  {out}\nBACKUP {path.with_suffix(path.suffix + '.bak')}"
              f"\nOriginal untouched. Review the diff, then move .new into place yourself.")
    else:
        print("\nDRY RUN - nothing written. Re-run with --commit.")

if __name__ == "__main__":
    main()
